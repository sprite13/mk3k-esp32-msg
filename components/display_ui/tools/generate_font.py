#!/usr/bin/env python3
"""Generate the fixed 12x20 UI bitmap font from a pinned Noto source."""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import urllib.request

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

SOURCE_COMMIT = "ffebf8c1ee449e544955a7e813c54f9b73848eac"
SOURCE_URL = (
    "https://raw.githubusercontent.com/notofonts/noto-fonts/"
    f"{SOURCE_COMMIT}/hinted/ttf/NotoSansMono/NotoSansMono-Regular.ttf"
)
SOURCE_SHA256 = "d9e2b23d19f8230be7146f409a52b1d23117e635e28f2e2892cf91b7382f325b"
WIDTH = 12
HEIGHT = 20
SIZE = 16
BASELINE = 16
PUNCTUATION = (
    0x00AB,
    0x00BB,
    *range(0x2010, 0x2016),
    *range(0x2018, 0x2020),
    0x2022,
    0x2026,
    0x2039,
    0x203A,
)


def source_bytes(path: pathlib.Path | None) -> bytes:
    data = path.read_bytes() if path else urllib.request.urlopen(SOURCE_URL).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"font SHA-256 mismatch: {digest}")
    return data


def glyph_rows(font: ImageFont.FreeTypeFont, codepoint: int) -> tuple[int, ...]:
    character = chr(codepoint)
    left, top, right, bottom = font.getbbox(character, anchor="ls")
    glyph_width = max(1, right - left)
    glyph_height = max(1, bottom - top)
    glyph = Image.new("L", (glyph_width, glyph_height), 0)
    ImageDraw.Draw(glyph).text(
        (-left, -top), character, font=font, fill=255, anchor="ls", stroke_width=0
    )
    if glyph_width > WIDTH or glyph_height > HEIGHT:
        scale = min(WIDTH / glyph_width, HEIGHT / glyph_height)
        glyph_width = max(1, round(glyph_width * scale))
        glyph_height = max(1, round(glyph_height * scale))
        glyph = glyph.resize((glyph_width, glyph_height), Image.Resampling.LANCZOS)

    image = Image.new("L", (WIDTH, HEIGHT), 0)
    x = (WIDTH - glyph_width) // 2
    y = min(max(BASELINE + top, 0), HEIGHT - glyph_height)
    image.paste(glyph, (x, y))
    rows = []
    for y in range(HEIGHT):
        value = 0
        for x_pos in range(WIDTH):
            if image.getpixel((x_pos, y)) >= 128:
                value |= 1 << (WIDTH - 1 - x_pos)
        rows.append(value)
    if codepoint != 0x20 and not any(rows):
        raise SystemExit(f"blank generated glyph U+{codepoint:04X}")
    return tuple(rows)


def emit_array(name: str, start: int, end: int, rows: dict[int, tuple[int, ...]]) -> str:
    output = [f"static const uint16_t {name}[{end - start + 1}][DISPLAY_FONT_HEIGHT] = {{"]
    for codepoint in range(start, end + 1):
        values = ", ".join(f"0x{row:03X}U" for row in rows[codepoint])
        output.append(f"    /* U+{codepoint:04X} */ {{{values}}},")
    output.append("};")
    return "\n".join(output)


def emit_sparse_array(
    name: str, codepoints: tuple[int, ...], rows: dict[int, tuple[int, ...]]
) -> str:
    output = [
        f"static const uint32_t {name}_CODEPOINTS[{len(codepoints)}] = {{",
        "    " + ", ".join(f"0x{codepoint:04X}U" for codepoint in codepoints),
        "};",
        f"static const uint16_t {name}[{len(codepoints)}][DISPLAY_FONT_HEIGHT] = {{",
    ]
    for codepoint in codepoints:
        values = ", ".join(f"0x{row:03X}U" for row in rows[codepoint])
        output.append(f"    /* U+{codepoint:04X} */ {{{values}}},")
    output.append("};")
    return "\n".join(output)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()

    data = source_bytes(args.font)
    cache = args.output.parent / ".font-source.tmp.ttf"
    cache.write_bytes(data)
    try:
        cmap = TTFont(cache).getBestCmap()
        required = (
            list(range(0x20, 0x7F))
            + list(range(0x0400, 0x0500))
            + list(PUNCTUATION)
        )
        missing = [codepoint for codepoint in required if codepoint not in cmap]
        if missing:
            raise SystemExit("source lacks: " + ", ".join(f"U+{cp:04X}" for cp in missing))
        font = ImageFont.truetype(str(cache), SIZE)
        rows = {codepoint: glyph_rows(font, codepoint) for codepoint in required}
    finally:
        cache.unlink(missing_ok=True)

    text = f"""/* Generated by tools/generate_font.py; do not edit manually.
 * Source: NotoSansMono-Regular.ttf at noto-fonts {SOURCE_COMMIT}
 * SHA-256: {SOURCE_SHA256}
 * Rasterizer: Pillow {__import__('PIL').__version__}, 16 px, threshold 128
 * Font copyright 2015-2021 Google LLC; licensed under SIL OFL 1.1.
 */
#include "display_layout.h"

{emit_array("FONT_ASCII", 0x20, 0x7E, rows)}

{emit_array("FONT_CYRILLIC", 0x0400, 0x04FF, rows)}

{emit_sparse_array("FONT_PUNCTUATION", PUNCTUATION, rows)}

bool display_font_get_glyph(uint32_t codepoint, const uint16_t **rows)
{{
    if (rows == NULL) {{
        return false;
    }}
    if (codepoint >= 0x20U && codepoint <= 0x7EU) {{
        *rows = FONT_ASCII[codepoint - 0x20U];
        return true;
    }}
    if (codepoint >= 0x0400U && codepoint <= 0x04FFU) {{
        *rows = FONT_CYRILLIC[codepoint - 0x0400U];
        return true;
    }}
    for (size_t index = 0U;
         index < sizeof(FONT_PUNCTUATION_CODEPOINTS) /
                     sizeof(FONT_PUNCTUATION_CODEPOINTS[0]);
         ++index) {{
        if (codepoint == FONT_PUNCTUATION_CODEPOINTS[index]) {{
            *rows = FONT_PUNCTUATION[index];
            return true;
        }}
    }}
    *rows = NULL;
    return false;
}}
"""
    args.output.write_text(text, encoding="ascii")


if __name__ == "__main__":
    main()
